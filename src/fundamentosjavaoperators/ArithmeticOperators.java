package fundamentosjavaoperators;

public class ArithmeticOperators {

	public static void main(String[] args) {
		//Declaration of two variables of the same type
		int num1, num2;
		//Initialize the variable before using them
		num1 = 234;
		num2 = 10;
		System.out.println(num1 / num2);
		System.out.println(num1 + num2);
		System.out.println(num1 - num2);
		System.out.println(num1 * num2);
		
		
	}
}
