package fundamentosjava;

public class Forloops {

	public static void main(String[] args) {
		System.out.println("1");
		System.out.println("1");
		System.out.println("1");
		System.out.println("1");
		System.out.println("1");
		System.out.println("1");
		System.out.println("1");
		for (int i = 0; i < args.length; i++) {
			System.out.println(1);
		}
	}
}
